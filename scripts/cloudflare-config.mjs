import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { siteURL } from '../config/sites.mjs';

const config = JSON.parse(await readFile(new URL('../wrangler.jsonc', import.meta.url), 'utf8'));
assert.ok(!config.main && !config.services, 'El portfolio sólo sirve sus archivos estáticos');
assert.deepEqual(config.routes, [{ pattern: new URL(siteURL).hostname, custom_domain: true }]);
const html = await readFile(new URL('../public/index.html', import.meta.url), 'utf8');
const jsonLd = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1];
const hash = createHash('sha256').update(jsonLd.replaceAll('\r\n', '\n')).digest('base64');
const csp = `default-src 'none'; style-src 'self' 'unsafe-inline'; script-src 'self' 'sha256-${hash}'; img-src 'self'; font-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'; upgrade-insecure-requests`;
const headers = `# Generated by npm run cloudflare:config.\n/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n  X-Frame-Options: DENY\n  Permissions-Policy: camera=(), microphone=(), geolocation=()\n/\n  Content-Security-Policy: ${csp}\n/index.html\n  Content-Security-Policy: ${csp}\n/assets/*\n  Cache-Control: public, max-age=86400\n`;
const path = new URL('../public/_headers', import.meta.url);
if (process.argv.includes('--check')) {
  assert.equal((await readFile(path, 'utf8')).replaceAll('\r\n', '\n'), headers, 'Ejecutar npm run cloudflare:config');
} else await writeFile(path, headers);
console.log('OK: dominio y cabeceras de Cloudflare.');
